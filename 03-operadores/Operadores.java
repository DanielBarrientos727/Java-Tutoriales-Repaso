public class Operadores {
    
public static void main(String[] args) {

    int a = 10;
    float b = 20.5f;
    boolean c = true;
    char simbolo = 'A'; // solo comillas simples
    String nombre = "Daniel";
    
    System.out.println("Mi numero es " + a);
    System.out.println("Mi float es " + b);
    System.out.println("Mi boolean es " + c);
    System.out.println("Mi char es " + simbolo);
    System.out.println("Mi string es " + nombre);
    

}
}